const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const esbuild = require("esbuild");

const projectRoot = path.resolve(__dirname, "..");
const entry = path.join(projectRoot, ".vuepress/components/slime-rebuild.worker.js");
const outputDir = path.join(projectRoot, ".vuepress/public/js");
const generatedModule = path.join(
  projectRoot,
  ".vuepress/components/slime-worker-url.generated.js"
);

async function main() {
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2017"],
    minify: true,
    write: false
  });
  const contents = result.outputFiles[0].contents;
  const hash = crypto.createHash("sha256").update(contents).digest("hex").slice(0, 12);
  const filename = `slime-rebuild.${hash}.js`;

  fs.mkdirSync(outputDir, { recursive: true });
  for (const name of fs.readdirSync(outputDir)) {
    if (/^slime-rebuild(?:\.worker|\.[a-f0-9]{12})\.js$/.test(name) && name !== filename)
      fs.unlinkSync(path.join(outputDir, name));
  }
  fs.writeFileSync(path.join(outputDir, filename), contents);
  fs.writeFileSync(
    generatedModule,
    `// Generated by scripts/build-slime-worker.js\nexport default ${JSON.stringify(`/js/${filename}`)};\n`
  );
  console.log(`Built ${filename}`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
